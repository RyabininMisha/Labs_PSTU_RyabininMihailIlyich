// Задана строка из N*N цифр. Установить, можно ли, разбив строку
// на подстроки длиной N, записать их в строки двумерного массива
// N x N по одной цифре в одном элементе так, чтобы они в первом
// столбце расположились в порядке возрастания.
// ============================================================

#include <iostream>
#include <cstring>
#include <clocale>

using namespace std;

const int MAXN = 20;                    // максимальный размер матрицы

// Разбиение строки s на N подстрок длиной N и запись их в строки
// матрицы m (подстрока с номером i занимает строку i, по одной
// цифре в каждом элементе)
void fillMatrix(const char s[], int n, int m[][MAXN])
{
    for (int i = 0; i < n; i++)
        for (int j = 0; j < n; j++)
            m[i][j] = s[i * n + j] - '0';   // код символа -> цифра
}

// Обмен местами строк i и j матрицы m
void swapRows(int m[][MAXN], int i, int j)
{
    int tmp;
    for (int k = 0; k < MAXN; k++)
    {
        tmp       = m[i][k];
        m[i][k]   = m[j][k];
        m[j][k]   = tmp;
    }
}

// Сортировка строк матрицы по возрастанию первых элементов строки
// (пузырьковая сортировка). После неё первый столбец принимает
// наименьший из возможных вариантов расположения цифр.
void sortByFirstColumn(int m[][MAXN], int n)
{
    for (int i = 0; i < n - 1; i++)
        for (int j = 0; j < n - 1 - i; j++)
            if (m[j][0] > m[j + 1][0])
                swapRows(m, j, j + 1);
}

// Проверка: расположен ли первый столбец матрицы строго
// по возрастанию (каждый следующий элемент больше предыдущего)
bool isFirstColumnAscending(int m[][MAXN], int n)
{
    for (int i = 0; i < n - 1; i++)
        if (m[i][0] >= m[i + 1][0])
            return false;
    return true;
}

// Печать матрицы построчно
void printMatrix(const int m[][MAXN], int n)
{
    for (int i = 0; i < n; i++)
    {
        for (int j = 0; j < n; j++)
            cout << m[i][j] << " ";
        cout << endl;
    }
}

int main()
{
    setlocale(LC_ALL, "Russian");       // русский текст в консоли

    char s[MAXN * MAXN + 1];            // исходная строка цифр
    int  m[MAXN][MAXN];                 // двумерный массив N x N
    int  n;

    cout << "Введите размер N: ";
    cin >> n;
    if (n < 1 || n > MAXN)
    {
        cout << "Ошибка: N должно быть от 1 до " << MAXN << endl;
        return 1;
    }

    cout << "Введите строку из " << n * n << " цифр: ";
    cin >> s;
    if ((int)strlen(s) != n * n)
    {
        cout << "Ошибка: длина строки должна быть равна " << n * n << endl;
        return 1;
    }

    // Разбиваем строку на подстроки длиной N и записываем их в строки матрицы
    fillMatrix(s, n, m);

    cout << "\nПодстроки, записанные в строки массива (в порядке следования):"
         << endl;
    printMatrix(m, n);

    // Расставляем подстроки по строкам наилучшим образом:
    // сортируем строки по возрастанию первых цифр
    sortByFirstColumn(m, n);

    cout << "\nРасположение подстрок с первым столбцом по возрастанию:" << endl;
    printMatrix(m, n);

    // Проверяем, получился ли первый столбец строго возрастающим
    if (isFirstColumnAscending(m, n))
        cout << "\nОтвет: МОЖНО - подстроки можно записать в строки массива "
             << "так, что в первом столбце цифры расположены по возрастанию."
             << endl;
    else
        cout << "\nОтвет: НЕЛЬЗЯ - в первом столбце есть одинаковые цифры, "
             << "поэтому строгое возрастание недостижимо." << endl;

    return 0;
}
