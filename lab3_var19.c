/* Лабораторная работа № 3. Вариант № 19
 * Вычисление функции y = e^(2x) через разложение в степенной ряд:
 * S = 1 + 2x/1! + (2x)^2/2! + ... + (2x)^n/n!
 * а) сумма SN для заданного n = 20;
 * б) сумма SE для заданной точности eps = 0.0001;
 * Y = exp(2x) - точное значение функции.
 * x изменяется от a = 0.1 до b = 1 с шагом h = (b - a)/k, k = 10.
 */
#include <stdio.h>
#include <math.h>

#define A    0.1        /* начало диапазона            */
#define B    1.0        /* конец диапазона             */
#define K    10         /* число разбиений диапазона   */
#define N    20         /* заданное число слагаемых    */
#define EPS  0.0001     /* заданная точность           */

int main(void)
{
    double h = (B - A) / K;      /* шаг изменения x */
    double x, p, sn, se, y;
    int i, m;

    printf("               Вычисление функции\n");

    /* внешний арифметический цикл по параметру x */
    for (i = 0; i <= K; i++)
    {
        x = A + i * h;

        /* арифметический цикл: сумма n+1 слагаемых a0..aN */
        p = 1.0;                 /* a0 = (2x)^0/0! = 1 */
        sn = 0.0;
        for (m = 0; m <= N; m++)
        {
            sn += p;             /* добавляем слагаемое a_m */
            p *= 2.0 * x / (m + 1);   /* a_{m+1} = a_m*2x/(m+1) */
        }

        /* итерационный цикл: суммируем, пока очередное слагаемое >= eps */
        p = 1.0;
        se = 0.0;
        m = 0;
        do
        {
            se += p;
            m++;
            p *= 2.0 * x / m;
        } while (p >= EPS);      /* выход, когда слагаемое < eps */

        y = exp(2.0 * x);        /* точное значение функции */

        printf("X=%.2f   SN=%.6f   SE=%.6f   Y=%.6f\n", x, sn, se, y);
    }
    return 0;
}
